/* ---------- 第二部封面装置：盖一座房子要几辈人 ---------- */
dev('#gnFig', () => {
  /* [名字, 起, 止（null = 至今未完）, 地区, 说明] 年份可带小数 */
  const B = [
    ['胡夫大金字塔', -2580, -2560, '外', '约二十年'],
    ['帕特农神庙', -447, -432, '外', '主体十五年'],
    ['万神殿（哈德良重建）', 113, 125, '外', ''],
    ['圣索菲亚大教堂', 532, 537.9, '外', '不到六年'],
    ['赵州桥', 595, 605, '中', '约十年'],
    ['巴黎圣母院', 1163, 1345, '外', '近两百年'],
    ['沙特尔大教堂（重建）', 1194, 1220, '外', '大火后二十多年'],
    ['科隆大教堂', 1248, 1880, '外', '中间停工三百多年'],
    ['博韦大教堂', 1225, null, '外', '至今没有中殿'],
    ['佛罗伦萨大教堂', 1296, 1436, '外', '穹顶合拢算完'],
    ['南京明城墙', 1366, 1393, '中', ''],
    ['紫禁城', 1406, 1420, '中', '备料十年，主体三四年'],
    ['圣彼得大教堂', 1506, 1626, '外', ''],
    ['泰姬陵', 1632, 1653, '外', ''],
    ['圣家堂', 1882, null, '外', '仍在修建'],
    ['帝国大厦', 1930.2, 1931.3, '外', '约四百一十天'],
    ['悉尼歌剧院', 1959, 1973, '外', '计划四年'],
    ['巴黎圣母院（火后修复）', 2019.3, 2024.9, '外', ''],
    ['武汉火神山医院', 2020.065, 2020.09, '中', '约十天']
  ];
  const F = ['全部', '中国', '超过一个工匠的一辈子'];
  let cur = 0;
  btnRow($('#gnBtns'), F, cur, i => { cur = i; draw(); });
  const NOW = 2026;
  function draw(){
    const rows = B.map(b => ({n: b[0], d: (b[2] == null ? NOW : b[2]) - b[1], open: b[2] == null, r: b[3], s: b[4], a: b[1]}))
      .filter(r => cur === 0 || (cur === 1 && r.r === '中') || (cur === 2 && r.d > 40))
      .sort((x, y) => x.d - y.d);
    const W = 600, L = 150, R = 30, rowH = 22, H = 30 + rows.length * rowH;
    const lo = Math.log10(0.02), hi = Math.log10(1000);
    const X = d => L + (Math.log10(Math.max(d, 0.02)) - lo) / (hi - lo) * (W - L - R);
    let g = '';
    [[0.0274, '十天'], [0.25, '三个月'], [1, '一年'], [10, '十年'], [100, '一百年'], [1000, '一千年']].forEach(t => g += '<line x1="' + X(t[0]) + '" x2="' + X(t[0]) + '" y1="14" y2="' + (H - 10) + '" stroke="var(--rule)"/>' + txt(X(t[0]), 10, t[1], {s: 10.5, c: 'var(--ink-3)', halo: false}));
    g += '<line x1="' + X(40) + '" x2="' + X(40) + '" y1="14" y2="' + (H - 10) + '" stroke="var(--ink-3)" stroke-width="2" stroke-dasharray="4 3"/>' + txt(X(40), H - 1, '一个工匠干一辈子 ≈ 40 年', {s: 10.5, c: 'var(--ink-2)'});
    rows.forEach((r, i) => {
      const y = 22 + i * rowH, col = r.r === '中' ? 'var(--ter)' : 'var(--main)';
      g += txt(L - 6, y + 11, r.n, {s: 11.5, a: 'end', c: 'var(--ink)', halo: false});
      g += '<rect x="' + L + '" y="' + (y + 2) + '" width="' + Math.max(2, X(r.d) - L) + '" height="13" rx="2" fill="' + col + '" fill-opacity="' + (r.d > 40 ? .85 : .5) + '"' + (r.open ? ' stroke="' + col + '" stroke-dasharray="3 2"' : '') + '/>';
      const lab = (r.d < 1 ? Math.round(r.d * 365) + ' 天' : Math.round(r.d) + ' 年') + (r.open ? '，未完' : '') + (r.s ? ' · ' + r.s : '');
      g += txt(X(r.d) + 5, y + 12, lab, {s: 10.5, a: 'start', c: 'var(--ink-2)'});
    });
    const svg = $('#gnSvg'); svg.setAttribute('viewBox', '0 0 ' + W + ' ' + (H + 6)); svg.innerHTML = g;
    const long = rows.filter(r => r.d > 40);
    $('#gnSay').innerHTML = cur === 2 ? '这 ' + long.length + ' 座房子，动工那天在场的工匠，没有一个能干到它完工。最长的科隆大教堂和至今没盖完的博韦、圣家堂，跨过了二十多代人。<b>盖这样的房子，要相信一件自己看不到结局的事</b>。' :
      cur === 1 ? '中国的大工程大多很快：木构可以先在地上做构件，几年就能立起来；紫禁城花在备料上的时间，比盖的时间还长。火神山医院十天建成，用的是预制的集装箱式病房，第三部讲。' :
      '从十天到八百年。工期长短，不只取决于房子有多大，更取决于用什么材料、钱是不是一直有、有没有人一直想把它盖完。中世纪大教堂的工期常常以“代”计算，现代的摩天楼以“月”计算。';
  }
  draw();
});
