
/* ---------- 第十四章：游戏里的电脑有多大、多慢 ---------- */
dev('#machFig', () => {
  const R = [['你的卧室', 4 * 3.5 * 2.8, '约 4×3.5×2.8 米'], ['一间教室', 9 * 7 * 3.5, '约 9×7×3.5 米'], ['2010 年的 16 位运算器', 160 * 110 * 10, '160×110×10 格'], ['埃菲尔铁塔占的空间', 125 * 125 * 330, '约 125×125×330 米'], ['CraftGPT（2025 年）', 1020 * 260 * 1656, '1020×260×1656 格']];
  const lg = v => Math.log10(v);
  bars($('#machBars'), R.map((r, i) => [r[0], lg(r[1]), r[2], i === 4 ? 'var(--zhu)' : i === 2 ? 'var(--ter)' : 'var(--blu)']), lg(4.4e8) * 1.01, v => fmt(Math.pow(10, v)));
  /* CraftGPT：加速约 4 万倍时回答一句要约 2 小时 → 原速约 8 万小时 */
  const BASE = 2 * 40000;
  slider('machSp', v => fmt(Math.round(Math.pow(10, v / 10))) + ' 倍', v => {
    const sp = Math.pow(10, v / 10), h = BASE / sp;
    const s = h >= 24 * 365 ? (h / 24 / 365).toFixed(1) + ' 年' : h >= 48 ? (h / 24).toFixed(0) + ' 天' : h >= 1 ? h.toFixed(1) + ' 小时' : Math.round(h * 60) + ' 分钟';
    kv($('#machKv'), [['游戏加快到', fmt(Math.round(sp)) + ' 倍'], ['CraftGPT 回你一句话', '约 ' + s]]);
    $('#machSay').textContent = sp < 2 ? '用普通的游戏速度，回一句话要大约九年：你问它的时候上四年级，它回答的时候你已经快上大学了。' :
      sp < 30000 ? '作者用了一个专门给红石加速的服务器程序。加速越多，回答越快。' : '加速约四万倍，回一句话大约两个小时，这是作者自己说的数字。电脑这么快，还要两个小时，你就知道这台“方块电脑”有多慢了。';
  });
});
