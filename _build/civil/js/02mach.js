
/* ---------- 第二部封面装置：一百个上班的人里，几个替政府干活 ---------- */
dev('#pubFig', fig => {
  const D = [['挪威', 30], ['丹麦', 28], ['瑞典', 29], ['芬兰', 25], ['法国', 21], ['加拿大', 19], ['英国', 16], ['意大利', 13], ['美国', 15], ['西班牙', 16], ['德国', 11], ['荷兰', 12], ['韩国', 8], ['日本', 6]];
  let mode = 0;
  btnRow($('#pubSort'), ['从高到低', '从低到高', '先别排，我先猜'], 2, i => { mode = i; draw(); });
  function draw(){
    let rows = D.slice();
    if (mode === 0) rows.sort((a, b) => b[1] - a[1]);
    if (mode === 1) rows.sort((a, b) => a[1] - b[1]);
    const hide = mode === 2;
    bars($('#pubBars'), rows.map(r => [r[0], hide ? 0 : r[1], '', r[0] === '日本' && !hide ? 'var(--zhu)' : 'var(--main)']), 32, v => hide ? '?' : '约 ' + v + '%');
    $('#pubSay').innerHTML = hide ? '先猜一下：哪个国家最低？很多人会猜美国，因为“美国是小政府”。点上面的排序按钮揭晓。' :
      '最低的是<b>日本</b>，一百个上班的人里大约只有六个替政府干活；北欧国家最高，接近三成，因为那里的托儿所、养老院、医院大多是公立的，护工和教师都算政府雇员。<b>“官僚多不多”和“公务员多不多”是两回事</b>：日本的公务员很少，可它的官僚曾经被认为是世界上最有权力的官僚之一（第十六章）。';
  }
  draw();
});
