
/* ---------- 第三部封面装置：一张桌子，四代人 ---------- */
dev('#genFig', fig => {
  const svg = $('#genSvg'), R = $('#genR');
  const P = [['老范', 1956, 1996, 'var(--kraft)', '范德昌，1956 年省水利学校毕业分配进局'], ['老温', 1984, 2025, 'var(--main)', '温，1984 年中专毕业分配进局，跟着老范'], ['何姐', 2006, 2025, 'var(--zhu)', '何静，2006 年考进来，现任综合科科长'], ['许多', 2025, 2025, 'var(--grn)', '2025 年考进来，考了两次']];
  const E = [[1956, '全国工资改革，机关工作人员实行等级工资', '老'], [1978, '恢复高考后的第一批大学生入学；改革开放开始', '时'], [1985, '机关事业单位工资改革（结构工资）', '老'], [1991, '上海试行住房公积金', '房'], [1993, '《国家公务员暂行条例》施行；机关工资制度改革', '编'], [1994, '中央国家机关首次统一招考公务员', '编'], [1998, '停止住房实物分配，房改', '房'], [1999, '《住房公积金管理条例》', '房'], [2006, '《公务员法》施行', '编'], [2012, '八项规定', '车'], [2014, '公务用车制度改革', '车'], [2015, '机关事业单位养老保险制度改革（自 2014 年 10 月起）', '老'], [2016, '“房子是用来住的，不是用来炒的”', '房'], [2019, '公务员职务与职级并行；为基层减负', '时'], [2025, '2026 年度国考，约 371.8 万人通过资格审查', '编']];
  const W = 600, L = 46, X = y => L + (y - 1955) / 71 * (W - L - 12);
  function draw(){
    const y0 = +R.value;
    $('#genRO').textContent = y0 + ' 年';
    let g = '';
    [1960, 1970, 1980, 1990, 2000, 2010, 2020].forEach(y => g += '<line x1="' + X(y) + '" x2="' + X(y) + '" y1="6" y2="170" stroke="var(--rule)" stroke-dasharray="2 3"/>' + txt(X(y), 186, y, {s: 10.5, c: 'var(--ink-3)', halo: false}));
    P.forEach((p, i) => {
      const y = 10 + i * 28;
      g += txt(L - 6, y + 15, p[0], {s: 12.5, a: 'end', c: p[3], halo: false});
      g += '<rect x="' + X(p[1]) + '" y="' + y + '" width="' + Math.max(5, X(p[2] + 1) - X(p[1])) + '" height="20" rx="3" fill="' + p[3] + '" opacity="' + (y0 >= p[1] && y0 <= p[2] ? 0.9 : 0.35) + '"/>';
    });
    E.forEach(e => g += '<circle cx="' + X(e[0]) + '" cy="' + (e[0] === y0 ? 140 : 140) + '" r="' + (e[0] === y0 ? 7 : 4) + '" fill="' + (e[0] === y0 ? 'var(--zhu)' : 'var(--ink-3)') + '"/>');
    g += txt(L - 6, 144, '事件', {s: 12, a: 'end', c: 'var(--ink-2)', halo: false});
    g += '<line x1="' + X(y0 + 0.5) + '" x2="' + X(y0 + 0.5) + '" y1="2" y2="172" stroke="var(--ink)" stroke-width="1.5"/>';
    svg.setAttribute('viewBox', '0 0 ' + W + ' 192'); svg.innerHTML = g;
    const who = P.filter(p => y0 >= p[1] && y0 <= p[2]);
    const ev = E.filter(e => e[0] === y0), near = E.filter(e => Math.abs(e[0] - y0) <= 2 && e[0] !== y0);
    $('#genSay').innerHTML = y0 + ' 年，综合科里：' + (who.length ? who.map(p => '<b style="color:' + p[3] + '">' + p[0] + '</b>').join('、') : '（没有这四个人）') + '。' +
      (ev.length ? '<br>这一年：<b>' + ev.map(e => e[1] + '（见“' + e[2] + '”）').join('；') + '</b>。' : near.length ? '<br>前后两年：' + near.map(e => e[0] + ' 年 ' + e[1]).join('；') + '。' : '<br>这一年没有列出的大事。对营盘里的人来说，大多数年份都是这样过去的。');
  }
  R.addEventListener('input', draw); draw();
});
