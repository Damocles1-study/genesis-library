
/* ---------- 装置 8：用谁来管 ---------- */
dev('#whoFig', fig => {
  const svg = $('#whoSvg'), say = $('#whoSay');
  // 每种人：控制力曲线 c(t)、能力曲线 a(t)，t 为 0—200 年
  const K = [
    {n: '贵族', c: t => 55 - 25 * (t / 200), a: t => 50 - 10 * (t / 200),
      s: '贵族一开始就有自己的地盘和兵，君主说了算的程度不高，而且随着爵位一代代世袭，越来越低。能力全看投胎：有的儿子能干，有的只会打猎。这是欧洲封建时代和西周的样子：<b>国王常常只是最大的那个贵族</b>。'},
    {n: '宦官', c: t => t < 80 ? 85 - t * 0.05 : 81 - (t - 80) * 0.45, a: t => 55 - 8 * Math.sin(t / 30),
      s: '头几十年非常好用：宦官没有儿子，只能靠你。可大约几代人以后，宦官之间结成了“宫里的家”，开始替幼主拿主意、掌握禁军、批红。东汉、唐朝后期、明朝后期都是这条曲线：<b>先是你的手，后来成了你的头</b>。'},
    {n: '奴隶出身的官', c: t => t < 120 ? 88 - t * 0.04 : 83 - (t - 120) * 0.55, a: t => t < 120 ? 78 : 78 - (t - 120) * 0.35,
      s: '从全国挑最聪明的孩子，精心培养，能力最高，又绝对依附于你。奥斯曼的十六世纪就是这条曲线的顶点。一百多年后，他们开始结婚、让儿子接班、经商、哗变，“征集”停了，能力下滑，控制力崩塌。<b>最后要用大炮才能收回来</b>。'},
    {n: '考试出身的文官', c: t => 70 - 8 * Math.sin(t / 45), a: t => 66 - 6 * (t / 200),
      s: '控制力和能力都不是最高，但最稳：文官有同年、同乡、门生，会结党、会扯皮，可他们的位子不能世袭，每一代都要重新考，没有哪一群人能把权力永久攥在手里。<b>它不是最好用的工具，却是最不容易反噬主人的工具</b>。这大概是科举能延续一千三百年的原因之一。'}
  ];
  let k = 0, seed = 1;
  btnRow($('#whoBtns'), K.map(x => x.n), 0, i => { k = i; run(); });
  function run(){
    const r = rng(seed++), o = K[k];
    const c = [], a = [];
    for (let t = 0; t <= 200; t += 5) { c.push([t, clamp(o.c(t) + (r() - 0.5) * 8, 2, 98)]); a.push([t, clamp(o.a(t) + (r() - 0.5) * 8, 2, 98)]); }
    lineChart(svg, [{color: 'var(--zhu)', pts: c, w: 2.8}, {color: 'var(--main)', pts: a, dash: '6 4'}], {xmin: 0, xmax: 200, ymin: 0, ymax: 100, yt: [0, 25, 50, 75, 100], xt: [0, 50, 100, 150, 200], xf: v => v + ' 年', H: 230});
    say.innerHTML = '<b>' + o.n + '</b>：' + o.s;
  }
  run();
});
