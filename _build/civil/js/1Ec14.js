
/* ---------- 装置 15：换届时换掉多少人 ---------- */
dev('#apFig', fig => {
  // [国家, 政治任命约数, 中央政府文职约数（万）, 说明]
  const D = [['美国', 4000, 220, '约四千个，其中一千多个须参议院批准'], ['法国', 1200, 250, '部长办公室成员 + 可自由任免的高级职位'], ['英国', 240, 51, '大臣约一百二十 + 特别顾问约一百二十'], ['德国', 250, 50, '部长、议会国务秘书 + “政治官员”'], ['日本', 80, 59, '大臣、副大臣、政务官、辅佐官']];
  let mode = 0;
  btnRow($('#apMode'), ['绝对人数', '每一万个文职里几个'], 0, i => { mode = i; draw(); });
  function draw(){
    const rows = D.map(d => [d[0], mode ? d[1] / d[2] : d[1], d[3], d[0] === '美国' ? 'var(--zhu)' : 'var(--main)']);
    const mx = Math.max(...rows.map(r => r[1]));
    bars($('#apBars'), rows, mx * 1.05, v => mode ? '约 ' + v.toFixed(1) : '约 ' + v.toLocaleString());
    $('#apSay').innerHTML = mode ? '按比例算，美国每一万个联邦文职人员里有十几个是政治任命，英德法大约是几个，日本更少。<b>差别不在一个数量级上</b>：美国新总统带进来的人，能一直伸到各部的中层。' :
      '美国换一届政府要换掉约四千人；英国、德国大约是两三百人，日本不到一百人。法国的数字不小，但大多是部长身边的办公室班子，各部的职业文官基本不动。';
  }
  draw();
});
