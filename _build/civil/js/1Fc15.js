
/* ---------- 装置 16：毕业名次决定一生 ---------- */
dev('#enaFig', fig => {
  // 去向按“受追捧程度”排序：[名字, 名额, 通常通向]
  const C = [['财政监察总署', 5, '审计全国财政，常去部长办公室和大银行、大企业当高管'], ['行政法院', 6, '审理告政府的案子、给政府起草法令，常任部长办公室主任、大公司法务首脑'], ['审计法院', 6, '审计公共账目，同样是政坛和商界的跳板'], ['外交部', 8, '驻外使馆，三十年后可能当上大使'], ['省长系统', 8, '从专区区长做起，二十年后当省长'], ['文职行政官（各部）', 57, '在各部当科长、处长、司长，一辈子在一个领域深耕']];
  let mode = 0;
  btnRow($('#enaMode'), ['2022 年以前', '2022 年以后'], 0, i => { mode = i; draw(); });
  const R = $('#enaR');
  R.addEventListener('input', draw);
  function draw(){
    const rk = +R.value;
    $('#enaRO').textContent = '第 ' + rk + ' 名';
    // 前 rk-1 名的人按受欢迎程度依次挑走名额
    let taken = rk - 1;
    const left = C.map(c => { const t = Math.min(c[1], taken); taken -= t; return c[1] - t; });
    if (mode === 1) {
      bars($('#enaBars'), [['国家行政官（统一入职）', 90, '所有毕业生', 'var(--main)']], 90, v => '90 人');
      $('#enaSay').innerHTML = '新规矩：不管第一名还是第九十名，都先进入同一个“国家行政官”职系，去部委、地方或一线工作几年，<b>之后再通过选拔进入各个大团</b>。二十五岁那一次排名的分量小了很多；可几年后的选拔看什么、谁来选，就成了新的问题。';
      return;
    }
    bars($('#enaBars'), C.map((c, i) => [c[0], left[i], '剩 ' + left[i] + ' / ' + c[1], left[i] ? (i < 3 ? 'var(--zhu)' : 'var(--main)') : 'var(--rule)']), 8, v => v ? '可选' : '没了');
    const best = left.findIndex(x => x > 0);
    const c = C[best];
    $('#enaSay').innerHTML = '轮到第 ' + rk + ' 名时，最好的选择是<b>' + c[0] + '</b>：' + c[2] + '。' +
      (best < 3 ? (rk >= 15 ? '' : '你挤进了“大团”。同届人一辈子都会记得这一点。') :
       rk <= 20 ? '只差几名，你就和三大团擦肩而过了。名次之间的分差，可能只有零点几分。' : '大部分埃纳克走的是这条路：不出名，但国家的大部分日常管理靠他们。');
  }
  draw();
});
