
/* ---------- 装置 29：哪一样代价会咬你 ---------- */
dev('#fitFig', fig => {
  // 每题：文字，影响 [约束, 慢, 磨, 背锅, 难退出] 的权重，影响 [稳定, 保障, 意义, 节奏] 的权重
  const Q = [
    ['我很在意收入每个月都一样，不想有大起大落。', [0, 0, 0, 0, -0.5], [2, 1, 0, 0]],
    ['我希望下班以后的时间完全属于自己，想做副业或兼职。', [2, 0, 0, 0, 0], [0, 0, 0, 1]],
    ['做一件事要等很多人点头，我会非常烦躁。', [0.5, 2, 0.5, 0, 0], [0, 0, 0, -0.5]],
    ['我能把一件重复的事情认认真真做上几百遍。', [0, 0, -2, 0, 0], [0.5, 0, 0.5, 0.5]],
    ['我希望自己的成绩被看见，做得好就要有回报。', [0, 1, 0.5, 1, 0], [0, 0, 0, -0.5]],
    ['帮一个陌生人把事办好，会让我高兴一整天。', [0, 0, -0.5, 0, 0], [0, 0, 2, 0]],
    ['我想在三十岁以前多试几种工作，再决定长期做什么。', [0.5, 0.5, 0, 0, 2], [0, 0, 0, 0]],
    ['想到老了以后有一笔稳定的养老金，我就心里踏实。', [0, 0, 0, 0, -0.5], [0.5, 2, 0, 0]]
  ];
  const CN = ['约束', '慢', '磨', '背锅', '难以退出'], GN = ['稳定', '长期保障', '意义感', '规律的节奏'];
  $('#fitQ').innerHTML = Q.map((q, i) => '<div class="ctl" style="grid-template-columns:minmax(0,1fr) 8em"><span style="color:var(--ink)">' + q[0] + '</span><input type="range" min="-2" max="2" value="0" data-i="' + i + '"></div>').join('');
  function calc(){
    const v = $$('#fitQ input').map(x => +x.value);
    const c = CN.map(() => 2.5), g = GN.map(() => 2.5);
    v.forEach((a, i) => { Q[i][1].forEach((w, k) => c[k] += a * w * 0.6); Q[i][2].forEach((w, k) => g[k] += a * w * 0.6); });
    const cc = c.map(x => clamp(x, 0, 5)), gg = g.map(x => clamp(x, 0, 5));
    bars($('#fitCost'), CN.map((n, k) => [n, cc[k], '', 'var(--red)']), 5, x => x.toFixed(1));
    bars($('#fitGain'), GN.map((n, k) => [n, gg[k], '', 'var(--grn)']), 5, x => x.toFixed(1));
    const ci = cc.indexOf(Math.max(...cc)), gi = gg.indexOf(Math.max(...gg));
    const touched = v.some(x => x !== 0);
    const sc = gg.reduce((s, x) => s + x, 0) - cc.reduce((s, x) => s + x, 0) * 0.8;
    $('#fitSay').innerHTML = !touched ? '先拖动上面的滑块，按你的真实想法回答。' :
      '对你来说，最重的代价是<b>“' + CN[ci] + '”</b>，最值钱的好处是<b>“' + GN[gi] + '”</b>。' +
      (sc > 3 ? '好处的分量明显压过了代价，这份工作和你的脾气比较合。可以再问自己一句：五年后，我还会这样回答吗？' :
       sc < -2 ? '代价的分量更重。如果你正在备考，这不是说你不该考，而是提醒你：进去以后，这几样东西会每天陪着你，最好提前想好怎么和它们相处。' :
       '好处和代价差不多。这种时候，真正能帮你决定的，往往是一个具体的岗位、一个具体的城市、一群具体的同事，而不是“体制内”这三个字。');
  }
  $('#fitQ').addEventListener('input', calc); calc();
});
