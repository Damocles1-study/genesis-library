/* ---------- 第三部封面装置：一百二十年：人、粮和氮 ---------- */
dev('#nzFig', () => {
  const POP = [[1900, 1.65], [1920, 1.86], [1940, 2.3], [1950, 2.5], [1961, 3.07], [1970, 3.7], [1980, 4.44], [1990, 5.33], [2000, 6.15], [2010, 6.99], [2020, 7.84]];
  const CER = [[1950, 690], [1961, 877], [1970, 1190], [1980, 1550], [1990, 1950], [2000, 2060], [2010, 2470], [2020, 2990]];
  const NIT = [[1910, 0.4], [1930, 1.3], [1950, 3.7], [1961, 11.6], [1970, 31.8], [1980, 60.8], [1990, 77], [2000, 81], [2010, 104], [2020, 113]];
  const S = [['世界人口（亿）', POP, 'var(--blu)', v => (v * 10).toFixed(0) + ' 亿人'], ['谷物产量', CER, 'var(--grn)', v => (v / 100).toFixed(1) + ' 亿吨'], ['氮肥用量', NIT, 'var(--red)', v => v.toFixed(0) + ' 百万吨氮']];
  let mode = 0;
  btnRow($('#nzMode'), ['以 1961 年为 1', '以 2020 年为 100%'], 0, i => { mode = i; draw(); });
  const at = (a, y) => { for (let i = 1; i < a.length; i++) if (y <= a[i][0]) return lerp(a[i - 1][1], a[i][1], (y - a[i - 1][0]) / (a[i][0] - a[i - 1][0])); return a[a.length - 1][1]; };
  function draw(){
    const ser = S.map(s => {
      const base = mode ? at(s[1], 2020) / 100 : at(s[1], 1961);
      return {pts: s[1].map(p => [p[0], p[1] / base]), color: s[2], w: 2.6, dots: true, dash: s[1] === NIT && mode === 0 ? '' : ''};
    });
    const ymax = mode ? 100 : 11;
    lineChart($('#nzChart'), ser, {xmin: 1900, xmax: 2020, ymin: 0, ymax, xt: [1900, 1920, 1940, 1960, 1980, 2000, 2020], yt: mode ? [0, 25, 50, 75, 100] : [0, 1, 2, 4, 6, 8, 10], yf: v => mode ? v + '%' : v + '×', H: 260,
      marks: [[1913, '哈伯—博施工厂投产'], [1966, '绿色革命']]});
    $('#nzLeg').innerHTML = S.map(s => '<span><i style="background:' + s[2] + '"></i>' + s[0].replace('（亿）', '') + '</span>').join('');
    const pr = at(POP, 2020) / at(POP, 1961), cr = at(CER, 2020) / at(CER, 1961), nr = at(NIT, 2020) / at(NIT, 1961);
    $('#nzSay').innerHTML = mode === 0 ? '1961 年到 2020 年，人口变成了原来的 ' + pr.toFixed(1) + ' 倍，谷物产量变成了 ' + cr.toFixed(1) + ' 倍，氮肥用量变成了 <b>' + nr.toFixed(1) + ' 倍</b>。粮食长得比人快，所以按人头算，吃的反而多了；代价之一，是地里撒下去的氮多了近十倍。' :
      '按 2020 年的量算，1950 年氮肥只用了今天的约 3%，人口却已经有今天的三分之一。<b>今天世界上大约一半的人，身体里的氮来自工厂</b>（第十八章讲这个估计从哪儿来）。';
  }
  draw();
});
