/* ---------- 装置 8：腌 ---------- */
dev('#slFig', () => {
  const AW = [[0, 1], [3.5, 0.98], [5, 0.97], [10, 0.935], [15, 0.895], [20, 0.84], [26, 0.75]];
  const aw = s => { for (let i = 1; i < AW.length; i++) if (s <= AW[i][0]) { const a = AW[i - 1], b = AW[i]; return lerp(a[1], b[1], (s - a[0]) / (b[0] - a[0])); } return 0.75; };
  const BUG = [
    ['大多数让肉、鱼发臭的细菌', '比如假单胞菌', 0.96, 0],
    ['大肠杆菌、沙门氏菌', '常见的致病菌', 0.945, 0],
    ['肉毒杆菌（常见的几型）', '毒素极强，没腌够的罐装、密封食物里要当心', 0.94, 0],
    ['乳酸菌', '做泡菜、酸菜、酸奶靠它', 0.925, 1],
    ['大多数酵母', '酱、酒里有用，也会让东西长白膜', 0.88, 2],
    ['金黄色葡萄球菌', '很耐盐，能在火腿、咸肉表面活下来', 0.86, 0],
    ['大多数霉菌', '长毛的那些', 0.80, 2],
    ['嗜盐菌', '在晒盐场、死海里也能活', 0.75, 2]
  ];
  const PRE = [['海水', 3.5], ['泡菜', 3], ['腌咸菜', 10], ['酱油', 17], ['咸鱼', 24]];
  const s = slider('slS', v => v.toFixed(1) + '%', () => draw());
  btnRow($('#slBtns'), PRE.map(p => p[0] + ' ' + p[1] + '%'), -1, i => { $('#slS').value = PRE[i][1]; $('#slSO').textContent = PRE[i][1].toFixed(1) + '%'; draw(); });
  function draw(){
    const S = s(), a = aw(S);
    kv($('#slKv'), [['水活度', a.toFixed(3)], ['相当于一升水放盐', Math.round(S / (100 - S) * 1000) + ' 克']]);
    $('#slBugs').innerHTML = BUG.map(b => '<div class="' + (a >= b[2] ? 'grow' : 'stop') + '"><span>' + b[0] + '<small>' + b[1] + ' · 最低约 ' + b[2] + '</small></span><b>' + (a >= b[2] ? '能长' : '长不了') + '</b></div>').join('');
    $('#slSay').innerHTML = S < 1.5 ? '几乎没放盐：什么都能长，这块肉明天就臭了。' :
      a >= 0.945 ? '盐不够多，有害的细菌还能长。泡菜就在这个区间：盐只负责先压一压，真正把坏菌挡住的是乳酸菌产的酸，所以泡菜要密封、要等它酸起来，没酸透的不能久放。' :
      a >= 0.88 ? '大多数致病菌长不了了，乳酸菌和酵母还能慢慢干活：这是腌咸菜、做酱的区间，咸，但还有“发酵”的香味。' :
      a >= 0.80 ? '只剩下耐盐的球菌、少数酵母和霉菌还能长：酱油、豆瓣酱在这里，靠盐和时间把豆子慢慢“熬”熟。' :
      '接近饱和：连大多数霉菌都长不了，这是咸鱼、腌肉的做法，能放一整个冬天，代价是吃之前要泡好久的水。';
  }
  draw();
});
