/* ---------- 装置 9：柴火账 ---------- */
dev('#fuFig', () => {
  const M = [['三块石头支锅', 1.8], ['泥灶 + 陶釜', 1.2], ['带烟囱的灶 + 铁锅', 0.8], ['燃气灶（折合）', 0.25]];
  const N = [['一家五口', 5], ['一个村子', 500], ['一座县城', 50000], ['北宋汴京', 1000000]];
  let m = 0, n = 0;
  btnRow($('#fuM'), M.map(x => x[0]), 0, i => { m = i; draw(); });
  btnRow($('#fuN'), N.map(x => x[0] + (x[1] >= 1e4 ? '（约 ' + fmt(x[1]) + '人）' : '')), 0, i => { n = i; draw(); });
  const YIELD = 3; // 吨 / 公顷 / 年
  function draw(){
    const ppl = N[n][1];
    const t = k => M[k][1] * ppl * 365 / 1000;             // 吨 / 年
    const area = k => t(k) / YIELD;                          // 公顷
    bars($('#fuBars'), M.map((x, k) => [x[0], t(k), '', k === m ? 'var(--main)' : 'var(--ink-3)']), t(0), v => v >= 1e4 ? fmt(v) + '吨' : v >= 10 ? Math.round(v) + ' 吨' : v.toFixed(1) + ' 吨');
    const a = area(m), km2 = a / 100;
    kv($('#fuKv'), [['一年烧掉', (t(m) >= 1e4 ? fmt(t(m)) + '吨' : t(m).toFixed(t(m) < 10 ? 1 : 0) + ' 吨')], ['要多大的林子', a >= 100 ? (km2 >= 100 ? Math.round(km2).toLocaleString() : km2.toFixed(1)) + ' 平方公里' : a.toFixed(a < 10 ? 1 : 0) + ' 公顷'], ['约等于', a >= 100 ? (km2 / 62).toFixed(km2 < 620 ? 1 : 0) + ' 个北京二环以内那么大' : Math.round(a * 1.4) + ' 个足球场']]);
    const big = N[n][1] >= 1e6;
    $('#fuSay').innerHTML = big && m === 3 ? '今天的大城市也一样要烧很多东西，只不过换成了从几千公里外用管道送来的天然气，和从电厂送来的电。林子不用砍了，账记到了别的地方。' : big ? '一百万人的城市，哪怕用最省柴的灶，每年也要砍掉相当于一个大县的林子，而且要年年从几十上百公里外运进城。<b>这就是汴京改烧煤的原因</b>：不是人们喜欢煤，是附近已经没有能砍的林子了。' :
      n === 0 ? '一家人一年要烧几吨柴，在古代，拾柴、砍柴、劈柴是家里的一项大活，常常落在孩子和女人身上。' :
      m === 0 ? '换一个带烟囱的灶，同样的饭，柴能省一半多，屋里的烟也少得多。今天很多国家推广“改良炉灶”，算的就是这笔账。' : '人一多，林子就不够了。古代很多地方的山被砍秃，水土流失，河流泛滥，起点就是千家万户的灶。';
  }
  draw();
});
