/* ---------- 装置 24：一个月的定量 ---------- */
dev('#rtFig', () => {
  /* [身份, 粮食斤/月（1955 年办法的中间值）] */
  const W = [['特别重的体力活（如搬运、采掘）', 50], ['重体力劳动者', 39.5], ['轻体力劳动者', 30], ['大中学生', 29.5], ['机关干部、职员、店员', 26.5], ['一般居民', 24.5]];
  const OIL = 0.4, MEAT = 1;           // 斤/月，示意
  const NOW = {grain: 22.8, meat: 5.8, oil: 1.5, egg: 2.3, milk: 2.1, fish: 2.3};
  let w = 4;
  btnRow($('#rtWho'), W.map(x => x[0]), 4, i => { w = i; draw(); });
  function draw(){
    const g = W[w][1];
    bars($('#rtBars'), [
      ['粮 · 定量', g, '能买的上限', 'var(--och)'], ['粮 · 2020 年代', NOW.grain, '人均，原粮', 'var(--grn)'],
      ['肉 · 定量', MEAT, '示意，很多地方更少', 'var(--och)'], ['肉 · 2020 年代', NOW.meat, '人均', 'var(--grn)'],
      ['油 · 定量', OIL, '示意，约四两', 'var(--och)'], ['油 · 2020 年代', NOW.oil, '人均，约数', 'var(--grn)'],
      ['蛋 · 2020 年代', NOW.egg, '定量年代常凭票，很少', 'var(--grn)'], ['奶 · 2020 年代', NOW.milk, '定量年代多为婴儿和病人特供', 'var(--grn)']
    ], 52, v => v.toFixed(v < 10 ? 1 : 0) + ' 斤');
    const kcal = g * 500 * 3.5 / 30 * 0.85 + OIL * 500 * 9 / 30 + MEAT * 500 * 3 / 30;
    $('#rtSay').innerHTML = '一个<b>' + W[w][0] + '</b>，每月最多能买 ' + g + ' 斤粮、约四两油、一斤左右的肉。按买足算，一天大约能吃到 ' + Math.round(kcal) + ' 千卡，几乎全部来自粮食。' +
      (g >= 39 ? '干重活的人粮多，可也几乎只有粮：一天要啃两三斤馒头窝头才顶得住。' : g <= 26.5 ? '定量不算少，但油和肉太少，人总觉得“肚子里没油水”，所以粮食吃得更多。' : '') +
      '今天平均每人每月直接吃的粮食比那时还少，<b>肉是那时的五六倍，油是三四倍</b>；热量的来源从“几乎全是粮”变成了一半左右来自肉、油、糖和别的东西。';
  }
  draw();
});
