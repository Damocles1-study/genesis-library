/* romeMap(o)：medMap 加上北方补丁和两条界河；返回值与 medMap 相同 */
function romeMap(o){
  const m = medMap(o);
  let g = m.svg;
  if (o.lat1 > 47) {
    g += '<path d="' + m.poly(NORTH.sea) + '" fill="var(--sea)"/>';
    g += '<path d="' + m.line(NORTH.coast) + '" fill="none" stroke="var(--ink-3)" stroke-width=".7"/>';
    g += '<path d="' + m.poly(NORTH.brit) + m.poly(NORTH.ire) + '" fill="var(--land)" stroke="var(--ink-3)" stroke-width=".7" stroke-linejoin="round"/>';
  }
  g += '<path d="' + m.line(NORTH.rhine) + m.line(NORTH.danube) + '" fill="none" stroke="var(--sea)" stroke-width="2.2" stroke-linecap="round"/>';
  m.svg = g;
  return m;
}
