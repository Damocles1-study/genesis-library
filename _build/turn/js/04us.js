/* ---------- 第四部封面装置：两百五十年，世界的工厂在哪儿 ---------- */
dev('#covFig4', fig => {
  const C = [['中国', '#c9573a'], ['印度', '#e08a2e'], ['英国', '#3a6ea5'], ['美国', '#2a9d9a'], ['德国', '#7a7a7a'], ['法国', '#7d5ba6'], ['俄国 / 苏联', '#a0785a'], ['日本', '#d16b8f'], ['其他', '#b9ad95']];
  // 年份 → 份额（%）。1750—1980：大致依据拜罗克（Bairoch 1982）；1990 以后：大致依据联合国制造业增加值。粗略取整，示意。
  const D = [
    [1750, [32.8, 24.5, 1.9, 0.1, 2.9, 4.0, 5.0, 3.8]], [1800, [33.3, 19.7, 4.3, 0.8, 3.5, 4.2, 5.6, 3.5]], [1830, [29.8, 17.6, 9.5, 2.4, 3.5, 5.2, 5.6, 2.8]],
    [1860, [19.7, 8.6, 19.9, 7.2, 4.9, 7.9, 7.0, 2.6]], [1880, [12.5, 2.8, 22.9, 14.7, 8.5, 7.8, 7.6, 2.4]], [1900, [6.2, 1.7, 18.5, 23.6, 13.2, 6.8, 8.8, 2.4]],
    [1913, [3.6, 1.4, 13.6, 32.0, 14.8, 6.1, 8.2, 2.7]], [1928, [3.4, 1.9, 9.9, 39.3, 11.6, 6.0, 5.3, 3.3]], [1938, [3.1, 2.4, 10.7, 31.4, 12.7, 4.4, 9.0, 5.2]],
    [1953, [2.3, 1.7, 8.4, 44.7, 5.9, 3.2, 10.7, 2.9]], [1963, [3.5, 1.8, 6.4, 35.1, 6.4, 3.8, 14.2, 5.1]], [1973, [3.9, 2.1, 4.9, 33.0, 5.9, 3.5, 14.4, 8.8]],
    [1980, [5.0, 2.3, 4.0, 31.5, 5.3, 3.3, 14.8, 9.1]], [1990, [3.5, 1.5, 4.0, 22, 9, 4, 4, 17]], [2000, [7, 1.5, 4, 25, 7, 3.5, 1, 16]],
    [2010, [19, 2.5, 2.5, 18, 6, 2.5, 2, 11]], [2020, [29, 3, 1.8, 16.5, 5, 1.8, 1.5, 7]]
  ];
  const at = y => { let i = 0; while (i < D.length - 2 && D[i + 1][0] <= y) i++; const a = D[i], b = D[i + 1], t = clamp((y - a[0]) / (b[0] - a[0]), 0, 1); const v = a[1].map((x, j) => lerp(x, b[1][j], t)); v.push(Math.max(0, 100 - v.reduce((p, q) => p + q, 0))); return v; };
  const R = $('#cvR'), svg = $('#cvSvg');
  $('#cvLeg').innerHTML = C.map(c => '<span><i style="background:' + c[1] + '"></i>' + c[0] + '</span>').join('');
  const W = 600, H = 230, L = 34, Rr = 10, T = 10, B = 26;
  const X = y => L + (y - 1750) / 270 * (W - L - Rr), Y = v => T + (1 - v / 100) * (H - T - B);
  let base = '';
  const ys = []; for (let y = 1750; y <= 2020; y += 2) ys.push(y);
  const vals = ys.map(at);
  for (let j = C.length - 1; j >= 0; j--) {
    const top = vals.map(v => v.slice(0, j + 1).reduce((p, q) => p + q, 0)), bot = vals.map(v => v.slice(0, j).reduce((p, q) => p + q, 0));
    base += '<path d="M' + ys.map((y, i) => X(y).toFixed(1) + ',' + Y(top[i]).toFixed(1)).join('L') + 'L' + ys.slice().reverse().map((y, i) => X(y).toFixed(1) + ',' + Y(bot[bot.length - 1 - i]).toFixed(1)).join('L') + 'Z" fill="' + C[j][1] + '" fill-opacity="' + (j === 8 ? '.35' : '.85') + '"/>';
  }
  [1750, 1800, 1850, 1900, 1950, 2000].forEach(y => base += txt(X(y), H - 8, y, {s: 11, c: 'var(--ink-3)', halo: false}));
  [0, 50, 100].forEach(v => base += txt(L - 5, Y(v) + 4, v + '%', {s: 10.5, a: 'end', c: 'var(--ink-3)', halo: false}));
  const SAY = [
    [1800, '手工的时代。纺车和织机在哪儿，人就在哪儿：中国和印度加起来占了全世界一半以上。英国刚刚开始用水力纺纱（<a href="' + href('c33') + '">第三十三章</a>）。北美的十三个殖民地还在种烟草、晒鳕鱼，几乎不造什么东西。'],
    [1860, '机器来了。英国用一个世纪，从不到百分之二爬到了五分之一，印度的织工却成片地失了业。美国北方的工厂开始起来，南方还在种棉花，卖给英国的工厂（<a href="' + href('c42') + '">第四十二章</a>）。'],
    [1895, '南北战争之后的三十年，铁路、钢铁、石油：美国在十九世纪八九十年代超过了英国（<a href="' + href('c43') + '">第四十三章</a>）。英国的工厂还在转，只是别人转得更快。'],
    [1940, '一战打完，欧洲欠了美国一屁股债，美国一家的工业产出比后面五六个国家加起来还多（<a href="' + href('c45') + '">第四十五章</a>）。然后是大萧条。'],
    [1960, '二战打完，欧洲和日本的工厂炸成了瓦砾，美国的工厂一刻没停过：这几年它一家占了全世界的四成多（<a href="' + href('c46') + '">第四十六章</a>）。一个霸主很少站得这样高，<em>也不可能一直站这样高</em>。'],
    [1990, '欧洲和日本重新站了起来，苏联靠计划经济堆出了一大块重工业。美国的份额慢慢回落到三成上下，日本的汽车和电视机让底特律和华盛顿都很紧张（<a href="' + href('c48') + '">第四十八章</a>）。'],
    [2008, '冷战结束，苏联那一块几乎消失了。中国加入了世界贸易组织，工厂一座接一座地开工（<a href="' + href('c49') + '">第四十九章</a>）。'],
    [2021, '2010 年前后，中国的制造业产出超过了美国，回到了两百多年前那个位置。<em>两百多年转了一圈</em>：这只是一个数字，霸主还要看钱、看海军、看盟友、看规矩由谁来定（<a href="' + href('c50') + '">尾声</a>）。']
  ];
  R.addEventListener('input', go);
  function go(){
    const y = +R.value, v = at(y);
    $('#cvO').textContent = y + ' 年';
    svg.setAttribute('viewBox', '0 0 ' + W + ' ' + H);
    svg.innerHTML = base + '<line x1="' + X(y) + '" x2="' + X(y) + '" y1="' + T + '" y2="' + (H - B) + '" stroke="var(--ink)" stroke-width="2"/>' + '<line x1="' + X(1980.5) + '" x2="' + X(1980.5) + '" y1="' + T + '" y2="' + (H - B) + '" stroke="var(--card)" stroke-dasharray="2 3"/>';
    const order = C.map((c, i) => [c, v[i]]).filter(x => x[1] >= 0.5 && x[0][0] !== '其他').sort((a, b) => b[1] - a[1]);
    $('#cvBars').innerHTML = order.slice(0, 6).map(x => '<div class="row"><span class="nm">' + x[0][0] + '</span><span class="tr"><i style="width:' + (x[1] * 2) + '%;background:' + x[0][1] + '"></i></span><span class="v">' + Math.round(x[1]) + '%</span></div>').join('');
    const s = SAY.find(z => y < z[0]) || SAY[SAY.length - 1];
    $('#cvSay').innerHTML = '<b>' + y + ' 年，排第一的是' + order[0][0][0] + '。</b>' + s[1];
  }
  go();
});
