
/* ---------- 装置 22：银币里还剩多少银子 ---------- */
dev('#coinFig', fig => {
  // [年份, 皇帝, 含银量（%，大致）, 说明]
  const D = [
    [-20, '奥古斯都', 97, '第纳尔几乎是纯银的。一个士兵一年的饷是 225 个第纳尔。'],
    [64, '尼禄', 93, '尼禄减轻了第纳尔的重量，含银量也稍稍下调。没什么人注意到。'],
    [100, '图拉真', 89, '达契亚的金银矿撑着，还算体面。'],
    [161, '马可·奥勒留', 79, '瘟疫和北方的战争，开始往里掺铜。'],
    [180, '康茂德', 72, ''],
    [195, '塞维鲁', 55, '塞维鲁给军队大涨军饷，银币一下子掉到一半多一点。'],
    [215, '卡拉卡拉', 50, '新发行一种“双第纳尔”，面值两倍，含银只有一个半。'],
    [238, '马克西米努斯之后', 45, '一年换了六个皇帝的那一年。'],
    [244, '戈尔迪安三世', 40, ''],
    [253, '瓦勒良', 30, '两条战线同时着火。'],
    [260, '加里恩努斯', 15, '瓦勒良被俘，帝国裂成三块。'],
    [268, '加里恩努斯末年', 4, '“银币”成了镀一层银皮的铜币。'],
    [270, '克劳狄二世', 2, '几乎全是铜。'],
    [274, '奥勒良', 4.5, '奥勒良改革币制，在新钱上标出成色，想挽回信用。可物价在这之后才真正飞涨起来。'],
    [294, '戴克里先', 4, '又一次币制改革，新铸了较纯的银币和金币，可日常用的还是铜钱。'],
    [309, '君士坦丁', 3, '君士坦丁的金币“索利都斯”问世：每磅金子打 72 枚，此后七百年成色几乎不变。']
  ];
  const R = $('#cnR'), coin = $('#cnCoin'), svg = $('#cnSvg');
  R.addEventListener('input', go);
  function go(){
    const k = +R.value, d = D[k], s = d[2] / 100;
    $('#cnO').textContent = yr(d[0]) + ' 年';
    // 银币剖面：外圈一层银皮，里面按含银量的比例画银（浅）与铜（深）
    const r = 90, area = Math.PI * r * r;
    const rIn = Math.sqrt(Math.max(0, 1 - s) * area / Math.PI);   // 中间铜芯的半径
    coin.setAttribute('viewBox', '0 0 220 220');
    coin.innerHTML = '<circle cx="110" cy="110" r="' + r + '" fill="#cfd3d6" stroke="var(--ink-3)" stroke-width="2"/>' +
      '<circle cx="110" cy="110" r="' + rIn.toFixed(1) + '" fill="#a0522d"/>' +
      '<circle cx="110" cy="110" r="' + (r - 8) + '" fill="none" stroke="var(--ink)" stroke-opacity=".25" stroke-dasharray="2 4"/>' +
      txt(110, 116, d[2] + '% 银', {s: 20, w: true, c: '#211d1a', hc: '#cfd3d6'});
    const coins = 97 / d[2];
    kv($('#cnKV'), [['皇帝', d[1]], ['含银量', '约 ' + d[2] + '%'], ['要凑出奥古斯都时代一枚的银子', coins < 1.5 ? '约 ' + coins.toFixed(1) + ' 枚' : '约 ' + Math.round(coins) + ' 枚']]);
    lineChart(svg, [{color: 'var(--ink-3)', pts: D.map(p => [p[0], p[2]]), w: 1.5, dash: '3 3'}, {color: 'var(--main)', pts: D.slice(0, k + 1).map(p => [p[0], p[2]]), w: 3}],
      {H: 220, xmin: -30, xmax: 320, ymin: 0, ymax: 100, xt: [0, 100, 200, 300], xf: v => v ? v + ' 年' : '公元', yt: [0, 25, 50, 75, 100], yf: v => v + '%', marks: [[235, '三世纪危机']]});
    const say = $('#cnSay');
    say.className = 'say ' + (d[2] < 20 ? 'bad' : '');
    say.innerHTML = (d[3] || '　') + '<br><small>按银子算，同样一袋小麦，要付的钱是奥古斯都时代的 <b>' + (coins < 1.5 ? coins.toFixed(1) : Math.round(coins)) + '</b> 倍（示意）。' + (d[0] > 230 && d[0] < 274 ? '实际上，物价在很长一段时间里涨得没那么快，人们还在按老习惯收钱；等大家都回过神来，就是一下子的飞涨。' : '') + '</small>';
  }
  go();
});
