
/* ---------- 装置 23：西罗马的钱袋 ---------- */
dev('#westFig', fig => {
  // [地区, 税收分量（示意）, 丢掉的年份, 被谁拿走]
  const P = [
    ['意大利', 20, 477, '一直到最后'],
    ['阿非利加（迦太基一带）', 24, 439, '汪达尔人，439'],
    ['努米底亚、毛里塔尼亚', 8, 435, '汪达尔人，429—435'],
    ['西西里', 6, 468, '汪达尔人劫掠，460 年代'],
    ['撒丁、科西嘉', 3, 460, '汪达尔人，450—460 年代'],
    ['西班牙大部', 9, 430, '苏维汇人、汪达尔人、西哥特人，409 年起'],
    ['塔拉科（西班牙东北）', 3, 472, '西哥特人，472'],
    ['不列颠', 5, 410, '罗马军队撤走，410 前后'],
    ['阿基坦（高卢西南）', 6, 418, '西哥特人定居，418'],
    ['高卢北部', 8, 461, '法兰克人和自立的罗马将军，460 年代'],
    ['普罗旺斯（高卢东南）', 4, 476, '西哥特人，476'],
    ['潘诺尼亚、诺里库姆', 5, 433, '让给匈人，433 前后']
  ];
  const TOT = P.reduce((s, p) => s + p[1], 0);
  const R = $('#wsR'), svg = $('#wsSvg');
  const rev = y => P.reduce((s, p) => s + (y < p[2] ? p[1] : 0), 0) / TOT;
  const EV = [[406, '渡过莱茵河'], [410, '罗马被劫'], [439, '迦太基'], [455, '罗马再被劫'], [476, '奥多亚克']];
  R.addEventListener('input', go);
  function go(){
    const y = +R.value;
    $('#wsO').textContent = y + ' 年';
    $('#wsBars').innerHTML = P.map(p => { const on = y < p[2]; return '<div class="row"><span class="nm">' + p[0] + (on ? '' : '<small>' + p[3] + '</small>') + '</span><span class="tr"><i style="width:' + (p[1] / 24 * 100) + '%;background:' + (on ? 'var(--och)' : 'var(--rule)') + '"></i></span><span class="v">' + (on ? p[1] : '—') + '</span></div>'; }).join('');
    const pts = []; for (let t = 395; t <= y; t++) pts.push([t, rev(t) * 100]);
    lineChart(svg, [{color: 'var(--rule)', pts: [[395, 100], [476, 100]], w: 1, dash: '2 4'}, {color: 'var(--och)', pts, w: 3}],
      {H: 200, xmin: 395, xmax: 476, ymin: 0, ymax: 100, xt: [395, 410, 430, 450, 476], xf: v => v, yt: [0, 50, 100], yf: v => v + '%', marks: EV.filter(e => e[0] <= y)});
    const r = rev(y), army = Math.round(r * 250000 / 1000) * 1000;   // 395 年西部军队的纸面兵力按约 25 万示意
    kv($('#wsKV'), [['剩下的税收', Math.round(r * 100) + '%'], ['养得起的兵（示意）', army.toLocaleString()], ['要守的地方', P.filter(p => y < p[2]).length + ' 块']]);
    const say = $('#wsSay');
    say.className = 'say ' + (r < .5 ? 'bad' : '');
    say.innerHTML = y < 406 ? '帝国还完整。可莱茵河和多瑙河的防线，已经要靠住在帝国里面的蛮族同盟军来守了。'
      : y < 439 ? '丢了不列颠、西班牙、高卢西南，钱袋小了一圈。好在阿非利加还在：罗马城的粮和朝廷的钱，大头都从那里来。'
      : y < 455 ? '<b>迦太基丢了。</b>一年之间，西罗马失去了最肥的那一块。没有钱，就只能拿土地去换蛮族的兵，可土地给出去，又少一块税。'
      : y < 476 ? '剩下的税收只够养一支很小的军队。真正能打仗的，是蛮族将军手下的同盟军。皇帝是他们立的，也是他们废的。'
      : '<b>476 年。</b>剩下的只有意大利。奥多亚克的兵要意大利三分之一的地，皇帝给不出来，于是皇帝没了。';
  }
  go();
});
