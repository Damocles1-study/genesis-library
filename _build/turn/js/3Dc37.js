/* ---------- 装置 38：日落 ---------- */
dev('#sunsetFig', fig => {
  // [年份, 地方, 人口（百万，约）]：离开英国直接统治的年份（不含自治领）
  const L = [
    [1922, '爱尔兰自由邦', 3], [1922, '埃及（名义独立）', 14], [1932, '伊拉克', 3.5], [1947, '印度', 345], [1947, '巴基斯坦（含东巴）', 75],
    [1948, '缅甸', 18], [1948, '锡兰', 7], [1948, '巴勒斯坦', 2], [1956, '苏丹', 10], [1957, '加纳', 6.7], [1957, '马来亚', 6.3],
    [1960, '尼日利亚', 45], [1960, '塞浦路斯', .6], [1960, '英属索马里兰', .7], [1961, '坦噶尼喀', 10], [1961, '塞拉利昂', 2.3], [1961, '科威特', .3],
    [1962, '乌干达', 7], [1962, '牙买加', 1.6], [1962, '特立尼达和多巴哥', .9], [1963, '肯尼亚', 9], [1963, '新加坡、沙巴、砂拉越（并入马来西亚）', 3], [1963, '桑给巴尔', .3],
    [1964, '马拉维', 4], [1964, '赞比亚', 3.6], [1964, '马耳他', .3], [1965, '冈比亚', .4], [1966, '圭亚那', .6], [1966, '博茨瓦纳', .6], [1966, '莱索托', .9], [1966, '巴巴多斯', .25],
    [1967, '亚丁（南也门）', 1.2], [1968, '毛里求斯', .8], [1968, '斯威士兰', .4]
  ];
  const START = 600;   // 各地独立时人口之和，再加上 1970 年以后才离开或一直没离开的地方（约一千五百万），示意
  const Y = $('#snY'), svg = $('#snSvg2');
  const left = y => Math.max(5, START - L.filter(l => l[0] <= y).reduce((s, l) => s + l[2], 0));
  Y.addEventListener('input', go);
  function go(){
    const y = +Y.value;
    $('#snYo').textContent = y + ' 年';
    const pts = []; for (let t = 1920; t <= 1970; t++) pts.push([t, left(t)]);
    const c = lineChart(svg, [{color: 'var(--rule)', pts, w: 1.5, dash: '3 3'}, {color: 'var(--och)', pts: pts.filter(p => p[0] <= y), w: 3}],
      {H: 220, xmin: 1920, xmax: 1970, ymin: 0, ymax: 650, xt: [1920, 1930, 1940, 1950, 1960, 1970], yt: [0, 200, 400, 600], yf: v => v + '百万', marks: [[1947, '1947'], [1956, '苏伊士']]});
    // 落日
    const sunY = 220 - 30 - (left(y) / 650) * 150;
    svg.innerHTML = '<circle cx="560" cy="' + sunY.toFixed(1) + '" r="16" fill="var(--ter)" fill-opacity=".75"/>' + svg.innerHTML;
    const now = L.filter(l => l[0] === y), sofar = L.filter(l => l[0] <= y).length;
    kv($('#snKV2'), [['还没离开的地方（按独立时的人口）', '约 ' + Math.round(left(y)) + ' 百万人'], ['离开帝国的地方', sofar + ' 处'], ['这一年', now.length ? now.length + ' 处' : '—']]);
    const say = $('#snSay2');
    say.className = 'say' + (y >= 1947 ? ' bad' : '');
    say.innerHTML = (now.length ? '<b>' + y + ' 年：</b>' + now.map(l => l[1]).join('、') + '。<br>' : '') +
      (y < 1947 ? '帝国看起来还很大。可两次大战之间，爱尔兰、埃及、伊拉克已经走了，自治领在外交上和伦敦平起平坐，印度的独立运动一年比一年强。'
      : y < 1956 ? '1947 年：印度和巴基斯坦一走，英国统治下的人口一下子少了四分之三以上。<em>没有印度，就没有“日不落帝国”</em>。'
      : y < 1965 ? '苏伊士以后，撤退加快了。1960 年，首相麦克米伦在南非议会演说，说“变革之风”正吹过非洲大陆。十年里，几十个殖民地相继独立。'
      : '到 1970 年，剩下的大多是一些小岛和据点：香港（1997 年交还中国）、直布罗陀、福克兰群岛……太阳还是会照到英国的领土上，只是照到的地方很小了。');
  }
  go();
});
