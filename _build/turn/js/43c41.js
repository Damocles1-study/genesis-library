/* ---------- 装置 42：一块一块拼起来 ---------- */
dev('#landFig', fig => {
  // [年, 名称, 面积（万平方公里）, 价钱（百万美元，不含利息；0 = 没有付钱）, 怎么来的, 从谁手里, 说明]
  const A = [
    [1783, '独立时的领土', 231, 0, '条约', '英国', '《巴黎和约》把边界划到密西西比河。阿巴拉契亚山以西的土地几乎全是印第安各民族的，英国把它们一并“交给”了美国。'],
    [1803, '路易斯安那', 214, 15, '买', '法国', '拿破仑缺钱，海地的起义又打碎了他的美洲梦。这片地上住着奥塞奇、波尼、拉科塔、夏延等几十个民族，法国人真正控制的只有新奥尔良一带。'],
    [1819, '佛罗里达', 19, 5, '条约', '西班牙', '杰克逊前一年带兵闯进西属佛罗里达追打塞米诺尔人，西班牙守不住，干脆让了出来；美国替西班牙承担美国公民的五百万元索赔。'],
    [1845, '得克萨斯', 101, 0, '吞并', '得克萨斯共和国', '美国移民从墨西哥手里闹独立，九年后并入美国，成为一个蓄奴州。墨西哥从来没承认过它的独立。'],
    [1846, '俄勒冈', 74, 0, '条约', '英国', '和英国沿北纬四十九度线一分为二。竞选时喊的是“要么五十四度四十分，要么开战”。'],
    [1848, '墨西哥割让地', 137, 15, '战争', '墨西哥', '加利福尼亚、新墨西哥、亚利桑那、内华达、犹他……墨西哥连同得克萨斯一共失去了约一半的国土。签约前九天，加利福尼亚发现了金子。'],
    [1853, '加兹登购地', 8, 10, '买', '墨西哥', '为了修一条走南边的横贯大陆的铁路，从墨西哥手里又买了一小块沙漠。'],
    [1867, '阿拉斯加', 152, 7.2, '买', '俄国', '俄国刚在克里米亚战争中输给英法，怕守不住，宁可卖给美国也不想让英国拿去。当时很多美国人嘲笑这笔买卖是国务卿西华德的“冰箱”。三十年后，那里发现了金子。'],
    [1898, '夏威夷', 1.7, 0, '吞并', '（推翻了王国的）夏威夷共和国', '美国糖业种植园主在海军陆战队的保护下推翻了夏威夷女王，五年后被美国吞并。见第四十四章。']
  ];
  const ACRE = 247.1; // 每平方公里合多少英亩
  const Y = $('#ldY'), svg = $('#ldSvg');
  const COL = {'买': 'var(--och)', '条约': 'var(--main)', '吞并': 'var(--pur)', '战争': 'var(--red)'};
  Y.addEventListener('input', go);
  function go(){
    const y = +Y.value;
    $('#ldYo').textContent = y + ' 年';
    const got = A.filter(a => a[0] <= y), cur = got[got.length - 1];
    // 堆叠条：按时间顺序
    const W = 600, H = 120, L = 10, R = 10, tot = A.reduce((s, a) => s + a[2], 0);
    let x = L, g = '';
    A.forEach(a => {
      const w = a[2] / tot * (W - L - R), on = a[0] <= y;
      g += '<rect x="' + x.toFixed(1) + '" y="34" width="' + Math.max(1, w - 1.5).toFixed(1) + '" height="40" rx="2" fill="' + (on ? COL[a[4]] : 'var(--paper)') + '" fill-opacity="' + (on ? (a === cur ? 1 : .6) : 1) + '" stroke="var(--rule)"/>';
      if (w > 40) g += txt(x + w / 2, 59, a[1].length > 6 ? a[1].slice(0, 5) + '…' : a[1], {s: 11, c: on ? 'var(--card)' : 'var(--ink-3)', halo: false});
      x += w;
    });
    Object.keys(COL).forEach((k, i) => g += '<rect x="' + (L + i * 80) + '" y="92" width="12" height="12" rx="2" fill="' + COL[k] + '"/>' + txt(L + i * 80 + 18, 102, k, {s: 12, a: 'start', halo: false}));
    g += txt(L, 22, '今天美国本土加阿拉斯加、夏威夷（约 ' + Math.round(tot) + ' 万平方公里）里，每一块是哪一年、怎么来的', {s: 12, a: 'start', c: 'var(--ink-2)', halo: false});
    svg.setAttribute('viewBox', '0 0 ' + W + ' ' + H); svg.innerHTML = g;
    const area = got.reduce((s, a) => s + a[2], 0), money = got.reduce((s, a) => s + a[3], 0);
    kv($('#ldKV'), [['到这一年的面积', Math.round(area) + ' 万平方公里'], ['一共付了', money ? money.toFixed(1).replace('.0', '') + ' 百万美元' : '0'], [cur[1] + '：每英亩', cur[3] ? (cur[3] * 1e6 / (cur[2] * 1e4 * ACRE) * 100).toFixed(1) + ' 美分' : '没有付钱']]);
    $('#ldCards').innerHTML = got.map(a => '<div class="cd' + (a === cur ? ' on' : '') + '"><b>' + a[0] + ' · ' + a[1] + '</b><small>' + a[4] + ' · ' + a[5] + ' · ' + a[2] + ' 万平方公里' + (a[3] ? ' · ' + a[3] + ' 百万美元' : '') + '</small></div>').join('');
    const say = $('#ldSay');
    say.className = 'say' + (cur[4] === '战争' || cur[4] === '吞并' ? ' bad' : '');
    say.innerHTML = '<b>' + cur[0] + ' 年 · ' + cur[1] + '：</b>' + cur[6] + (y >= 1887 ? '<br><small>同一时期，在美国国内：1887 年的《道斯法》以后，印第安人手里的土地从一亿三千八百万英亩缩到了 1934 年的四千八百万英亩，<em>少掉的九千万英亩，没有出现在任何一张购地的账单上</em>。</small>' : '');
  }
  go();
});
