dev('#nsFig', fig => {
  // [项目, 北方, 南方, 单位, 说明]（1860 年前后，取整；有的只是比例）
  const BEFORE = [
    ['人口', 22, 9, '百万', '南方九百万人里，约三百五十万是被奴役的人，他们不会被征召去替主人打仗。'],
    ['制造业产值', 90, 10, '%', '北方占全国工业产出的九成左右。'],
    ['铁路', 22, 9, '千英里', '而且南方的铁路轨距不统一，很多线路互相接不上。'],
    ['生铁', 15, 1, '比例', '约十五比一。'],
    ['枪支', 32, 1, '比例', '约三十二比一。开战初期，南方很多兵扛的是自己家的猎枪。'],
    ['银行存款', 81, 19, '%', '北方的钱袋子深得多，所以它能收所得税、卖国债，南方只能印钞票。'],
    ['棉花', 0, 100, '%', '南方唯一的王牌。'],
  ];
  const AFTER = [
    ['军人死亡', 36, 26, '万（传统统计）', '北方死得更多，可北方的人口多得多。南方十三到四十三岁的白人男子，大约每五个里死了一个。'],
    ['财富变化', 50, -60, '%（示意）', '北方的财富在战争中继续增长；南方的财富蒸发了一大半（其中最大的一块，是“奴隶”这项资产不再存在）。'],
    ['纸币贬值', 2.5, 92, '倍（约）', '一块钱的联邦绿背钞票到战争最糟的时候只剩四成左右的价值；联盟国的纸币贬值了九十多倍。'],
    ['重获自由的人', 0, 4, '百万', '战前南方最大的一笔“资产”，变成了四百万没有土地、没有钱的自由人。'],
  ];
  // [年份, 被奴役人口（百万）, 棉花（百万包）]
  const GROW = [[1790, .70, .003], [1800, .89, .07], [1810, 1.19, .18], [1820, 1.54, .33], [1830, 2.01, .73], [1840, 2.49, 1.35], [1850, 3.20, 2.13], [1860, 3.95, 4.5]];
  let tab = 0;
  btnRow($('#nsTab'), ['开战时的家底', '打了四年之后', '棉花和锁链 1790—1860'], 0, i => { tab = i; go(); });
  function bars(D){
    return D.map(d => { const mx = Math.max(Math.abs(d[1]), Math.abs(d[2])) || 1;
      return '<div class="row"><span class="nm">' + d[0] + '<small>' + d[3] + '</small></span><span class="tr"><i style="width:' + (Math.abs(d[1]) / mx * 50) + '%;background:var(--main);left:auto;right:50%"></i><i style="width:' + (Math.abs(d[2]) / mx * 50) + '%;background:var(--red);left:50%"></i></span><span class="v">' + d[1] + ' : ' + d[2] + '</span></div>'; }).join('');
  }
  function go(){
    const svg = $('#nsSvg'), say = $('#nsSay');
    svg.parentNode.style.display = tab === 2 ? '' : 'none';
    if (tab < 2) {
      const D = tab ? AFTER : BEFORE;
      $('#nsBars').innerHTML = '<div class="legend"><span><i style="background:var(--main)"></i>北方（联邦）</span><span><i style="background:var(--red)"></i>南方（联盟国）</span></div>' + bars(D);
      say.className = 'say' + (tab ? ' bad' : '');
      say.innerHTML = tab ? '<b>打了四年。</b>' + D.map(d => d[4]).join('') : '<b>纸面上，南方没有赢面。</b>可南方不需要征服北方，只需要撑到北方不想打了，就像当年的美国人撑到英国人不想打了一样（第三十九章）。所以 1864 年的大选对南方来说至关重要：如果林肯输给主和的对手，南方就可能赢。那年 9 月谢尔曼攻下亚特兰大，林肯赢了。' + '<br><small>' + D.map(d => '<b>' + d[0] + '</b>：' + d[4]).join(' ') + '</small>';
    } else {
      $('#nsBars').innerHTML = '';
      const c = lineChart(svg, [{color: 'var(--red)', pts: GROW.map(g => [g[0], g[1]])}, {color: 'var(--och)', pts: GROW.map(g => [g[0], g[2]]), dash: '5 3'}],
        {H: 230, xmin: 1790, xmax: 1860, ymin: 0, ymax: 4.8, xt: [1790, 1800, 1810, 1820, 1830, 1840, 1850, 1860], yt: [0, 1, 2, 3, 4], yf: v => v + '', marks: [[1793, '轧棉机'], [1808, '禁止进口奴隶'], [1830, '印第安人迁移法']]});
      svg.innerHTML += txt(c.X(1859), c.Y(3.6) + 16, '被奴役人口（百万人）', {s: 11.5, a: 'end', c: 'var(--red)'}) + txt(c.X(1857), c.Y(4.5) - 4, '棉花（百万包）', {s: 11.5, a: 'end', c: 'var(--och)'});
      say.className = 'say bad';
      say.innerHTML = '<b>两条线一起往上走。</b>1808 年以后不能再从非洲进口奴隶了，被奴役的人口却在五十年里涨了三倍多，靠的是生育和从老蓄奴州往新棉花州的贩卖。棉花的产量涨得更快。<em>独立时很多人以为会自己消亡的奴隶制，被一台轧棉机和英国的纺纱厂救活了</em>。';
    }
  }
  go();
});
