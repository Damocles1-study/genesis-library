dev('#meritFig', fig => {
  // [年份, 联邦文职雇员（千人，约）, 考试录用比例 %（示意）]
  const D = [[1829, 10, 0], [1841, 18, 0], [1851, 26, 0], [1861, 37, 0], [1871, 51, 0], [1881, 100, 0], [1883, 131, 0], [1884, 131, 10.5], [1891, 157, 21], [1897, 192, 46],
    [1901, 239, 44], [1911, 396, 57], [1921, 562, 70], [1931, 610, 77], [1936, 820, 60], [1940, 1040, 72], [1945, 3800, 85], [1950, 1960, 86]];
  const EV = [
    [1829, '杰克逊上任', '“官职应该轮换”：杰克逊换掉了大约一成的联邦官员，换上自己的支持者。联邦政府这时只有一万人左右，大半在邮局。'],
    [1832, '“战利品归胜利者”', '马西参议员的一句话，给这个制度起了名字。'],
    [1861, '林肯上任', '内战前夕，林肯换掉了绝大多数由总统任命的官员。他抱怨说，打仗之外，他还得天天接见求官的人。'],
    [1881, '火车站的两枪', '加菲尔德被一个求官不成的人枪杀。这时联邦政府有十万人左右，没有一个是考试进来的。'],
    [1883, '《彭德尔顿法》', '一成左右的职位要考试录用，其余的仍然归总统。总统可以用行政命令扩大这个范围。'],
    [1889, '一个年轻的文官委员', '三十岁的西奥多·罗斯福当了六年文官委员，四处查处违规任命，和本党的政客们吵翻了天。'],
    [1897, '离任前的“罩”', '克利夫兰在第二任快结束时，一次把好几万个职位划进了考试录用的范围，其中不少是他自己任命的人。'],
    [1933, '新政', '罗斯福的新政新设了一大批机构，很多不在文官体系里，比例一度掉了下来。'],
    [1939, '《哈奇法》', '禁止联邦雇员参与党派竞选活动；1940 年又把大批新政机构的职位纳入了文官体系。'],
    [1945, '二战', '战时的联邦文职雇员一度超过三百五十万人，大多是临时招来的。']
  ];
  const at = y => { let i = 0; while (i < D.length - 2 && D[i + 1][0] <= y) i++; const a = D[i], b = D[i + 1], t = clamp((y - a[0]) / (b[0] - a[0]), 0, 1); return [lerp(a[1], b[1], t), y < 1884 ? 0 : lerp(a[2], b[2], t)]; };
  const Y = $('#mtY'), svg = $('#mtSvg');
  Y.addEventListener('input', go);
  function go(){
    const y = +Y.value, v = at(y);
    $('#mtYo').textContent = y + ' 年';
    const W = 600, H = 230, L = 52, R = 12, T = 12, B = 28;
    const X = t => L + (t - 1829) / 121 * (W - L - R), LY = n => T + (1 - Math.log10(n / 8) / Math.log10(4000 / 8)) * (H - T - B);
    let g = '';
    [10, 100, 1000].forEach(n => g += '<line x1="' + L + '" x2="' + (W - R) + '" y1="' + LY(n) + '" y2="' + LY(n) + '" stroke="var(--rule)"/>' + txt(L - 6, LY(n) + 4, n >= 1000 ? (n / 1000) + ' 百万' : n + ' 千', {s: 10.5, a: 'end', c: 'var(--ink-3)', halo: false}));
    [1830, 1860, 1890, 1920, 1950].forEach(t => g += txt(X(t), H - 9, t, {s: 10.5, c: 'var(--ink-3)', halo: false}));
    // 柱：每年一根细柱，全高 = 雇员，深色 = 考试录用部分（按比例画在对数刻度上只为示意）
    for (let t = 1829; t <= 1950; t += 3) {
      const a = at(t), top = LY(a[0]), base = H - B, h = base - top, x = X(t);
      g += '<rect x="' + (x - 1.6) + '" y="' + top + '" width="3.2" height="' + h + '" fill="var(--och)" fill-opacity="' + (t <= y ? .35 : .12) + '"/>';
      if (a[1] > 0) g += '<rect x="' + (x - 1.6) + '" y="' + (base - h * a[1] / 100) + '" width="3.2" height="' + (h * a[1] / 100) + '" fill="var(--main)" fill-opacity="' + (t <= y ? 1 : .3) + '"/>';
    }
    g += '<line x1="' + X(y) + '" x2="' + X(y) + '" y1="' + T + '" y2="' + (H - B) + '" stroke="var(--ink)" stroke-width="1.5"/>';
    g += '<rect x="' + (L + 6) + '" y="' + (T + 2) + '" width="10" height="10" fill="var(--main)"/>' + txt(L + 20, T + 11, '考试录用', {s: 11, a: 'start', halo: false}) + '<rect x="' + (L + 86) + '" y="' + (T + 2) + '" width="10" height="10" fill="var(--och)" fill-opacity=".35"/>' + txt(L + 100, T + 11, '可以换人', {s: 11, a: 'start', halo: false});
    svg.setAttribute('viewBox', '0 0 ' + W + ' ' + H); svg.innerHTML = g;
    const spoils = v[0] * (1 - v[1] / 100);
    kv($('#mtKV'), [['联邦文职雇员', fmt(v[0] * 1000) + ' 人'], ['考试录用', Math.round(v[1]) + '%'], ['换党时可以换掉的位子（最多）', fmt(spoils * 1000) + ' 个']]);
    const e = EV.filter(x => x[0] <= y).pop();
    const say = $('#mtSay');
    say.className = 'say' + (v[1] > 50 ? ' ok' : '');
    say.innerHTML = '<b>' + e[0] + ' · ' + e[1] + '：</b>' + e[2] + (v[1] === 0 ? '<br><small>这一年，每一个联邦职位都可以由赢了大选的党拿去分。</small>' : '');
  }
  go();
});
