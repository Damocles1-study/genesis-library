/* ---------- 装置 47：兵工厂与马歇尔计划 ---------- */
dev('#arsFig', fig => {
  const C = [['美国', '#2a9d9a'], ['苏联', '#a0785a'], ['英国', '#3a6ea5'], ['德国', '#7a7a7a'], ['日本', '#d16b8f']];
  // 每年军用飞机产量（架，常见整理取整）
  const AIR = {1939: [2141, 10382, 7940, 8295, 4467], 1940: [6086, 10565, 15049, 10247, 4768], 1941: [19433, 15735, 20094, 11776, 5088], 1942: [47836, 25436, 23672, 15409, 8861],
    1943: [85898, 34900, 26263, 28807, 16693], 1944: [96318, 40300, 26461, 39807, 28180], 1945: [46001, 20900, 12070, 7540, 11066]};
  // 马歇尔计划：[国家, 百万美元（约）, 人口百万（约 1950）]
  const MP = [['英国', 3297, 50.1], ['法国', 2296, 41.8], ['西德', 1448, 50], ['意大利', 1204, 46.6], ['荷兰', 1128, 10.1], ['比利时和卢森堡', 777, 8.9], ['希腊', 694, 7.6], ['奥地利', 468, 6.9],
    ['丹麦', 273, 4.3], ['挪威', 255, 3.3], ['土耳其', 137, 20.9], ['爱尔兰', 133, 3], ['瑞典', 107, 7], ['葡萄牙', 70, 8.4], ['冰岛', 43, .14]];
  let tab = 0, per = 0;
  btnRow($('#arTab'), ['飞机产量', '马歇尔计划：总数', '马歇尔计划：人均'], 0, i => { tab = i; go(); });
  const Y = $('#arY'); Y.addEventListener('input', go);
  function go(){
    const say = $('#arSay');
    $('#arCtl').style.display = tab === 0 ? '' : 'none';
    if (tab === 0) {
      const y = +Y.value, v = AIR[y], mx = 100000;
      $('#arYo').textContent = y + ' 年';
      let cum = C.map((c, i) => { let s = 0; for (let t = 1939; t <= y; t++) s += AIR[t][i]; return s; });
      $('#arBars').innerHTML = C.map((c, i) => '<div class="row"><span class="nm">' + c[0] + '<small>累计 ' + fmt(cum[i]) + '</small></span><span class="tr"><i style="width:' + (v[i] / mx * 100) + '%;background:' + c[1] + '"></i></span><span class="v">' + v[i].toLocaleString() + '</span></div>').join('');
      const axis = v[3] + v[4];
      say.className = 'say' + (v[0] > axis ? ' ok' : '');
      say.innerHTML = {1939: '<b>1939 年，美国造的飞机比日本还少。</b>美国陆军航空队只有一千多架能用的飞机，很多已经过时。', 1940: '<b>法国投降，英国拼命造飞机。</b>罗斯福提出了一个当时听起来像天方夜谭的目标：美国一年要造五万架飞机。', 1941: '<b>美国还没参战，订单已经来了。</b>英国和后来的苏联通过租借拿走了大量的飞机。', 1942: '<b>参战第一年，美国的产量就超过了德国和日本加起来。</b>汽车厂全部改造军需品，福特的威洛兰工厂开始用流水线造轰炸机。', 1943: '<b>一年八万多架。</b>德国在军备部长施佩尔的整顿下产量也翻了一番，可是两边的差距越拉越大。', 1944: '<b>将近十万架，相当于每五分钟一架。</b>德国和日本加起来不到七万架，而且缺油、缺飞行员，很多新飞机根本飞不上天。', 1945: '<b>战争结束，订单取消。</b>七年里美国一共造了三十万架左右，苏联十五万架左右，德国十二万架左右，日本八万架左右。'}[y];
    } else {
      const pc = tab === 2;
      const rows = MP.map(m => [m[0], pc ? m[1] / m[2] : m[1], m]).sort((a, b) => b[1] - a[1]);
      const mx = rows[0][1];
      $('#arBars').innerHTML = rows.map(r => '<div class="row"><span class="nm">' + r[0] + '</span><span class="tr"><i style="width:' + (r[1] / mx * 100) + '%;background:' + (r[0] === '希腊' ? 'var(--och)' : 'var(--main)') + '"></i></span><span class="v">' + (pc ? Math.round(r[1]) + ' 元/人' : (r[1] / 1000).toFixed(2) + ' 十亿') + '</span></div>').join('');
      say.className = 'say';
      say.innerHTML = pc ? '<b>按人头算，排第一的是冰岛</b>：十几万人拿到了四千多万美元，因为它是北大西洋上的战略要地，美国在那里有一个空军基地。希腊人均九十美元左右，排在前面；英国拿的总数最多，人均却排在中间。<em>钱给谁、给多少，看的不只是谁最穷，也看谁最重要</em>。'
        : '<b>英国、法国、西德、意大利拿走了一大半。</b>一百三十亿美元左右，相当于今天的一千多亿美元。苏联和东欧拒绝了。西德用卖援助物资收来的“对等基金”设了一个专门的周转基金，交给一家开发银行放贷，这笔基金今天还在德国周转（<b>存疑</b>具体数额）。希腊的那一行（黄色）里，有盐屿的面粉袋。';
    }
  }
  go();
});
