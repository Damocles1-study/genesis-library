/* ---------- 装置 49：黄金窗口 ---------- */
dev('#goldFig', fig => {
  // [年, 美国黄金储备（十亿美元，按 35 美元/盎司）, 外国人持有的美元债权（十亿美元）]（示意，粗略取整）
  const G = [[1950, 22.8, 8.9], [1952, 23.3, 10.5], [1955, 21.8, 13.5], [1958, 20.6, 16.2], [1960, 17.8, 21], [1962, 16, 24.1], [1964, 15.5, 27.6], [1965, 13.8, 29.1], [1967, 12.1, 35.7], [1968, 10.9, 38.5], [1970, 11.1, 47], [1971, 10.2, 67.8]];
  // [年, 油价（美元/桶，年均）, 通胀 %, 联邦基金利率 %]
  const O = [[1970, 1.8, 5.7, 7.2], [1972, 2.5, 3.3, 4.4], [1973, 3.3, 6.2, 8.7], [1974, 11.6, 11.1, 10.5], [1976, 12.8, 5.7, 5.1], [1978, 14, 7.6, 7.9], [1979, 31.6, 11.3, 11.2], [1980, 36.8, 13.5, 13.4], [1981, 35.9, 10.3, 16.4], [1982, 32.9, 6.2, 12.3], [1983, 29.6, 3.2, 9.1], [1985, 27.5, 3.6, 8.1], [1986, 14.4, 1.9, 6.8], [1988, 14.9, 4.1, 7.6], [1990, 23.7, 5.4, 8.1]];
  // [年, 一美元换多少日元]
  const J = [[1970, 360], [1971, 350], [1973, 272], [1975, 297], [1978, 210], [1980, 227], [1982, 249], [1985, 238], [1986, 168], [1987, 145], [1988, 128], [1990, 145]];
  const ip = (T, y, k) => { let i = 0; while (i < T.length - 2 && T[i + 1][0] <= y) i++; const a = T[i], b = T[i + 1]; return lerp(a[k], b[k], clamp((y - a[0]) / (b[0] - a[0]), 0, 1)); };
  let tab = 0;
  btnRow($('#gdTab'), ['黄金窗口 1950—1971', '油价、通胀、利率', '日元'], 0, i => { tab = i; go(); });
  const Y = $('#gdY'); Y.addEventListener('input', go);
  function go(){
    const svg = $('#gdSvg'), say = $('#gdSay');
    $('#gdCtl').style.display = tab === 0 ? '' : 'none';
    $('#gdKV').style.display = tab === 0 ? '' : 'none';
    if (tab === 0) {
      const y = +Y.value, g = ip(G, y, 1), f = ip(G, y, 2);
      $('#gdYo').textContent = y + ' 年';
      const c = lineChart(svg, [{color: 'var(--och)', pts: G.map(r => [r[0], r[1]]), w: 3}, {color: 'var(--red)', pts: G.map(r => [r[0], r[2]]), w: 3, dash: '6 3'}],
        {H: 230, xmin: 1950, xmax: 1971, ymin: 0, ymax: 70, xt: [1950, 1955, 1960, 1965, 1970], yt: [0, 20, 40, 60], yf: v => v + ' 十亿', marks: [[1960, '交叉'], [1968, '黄金池散伙']]});
      svg.innerHTML += '<line x1="' + c.X(y) + '" x2="' + c.X(y) + '" y1="14" y2="200" stroke="var(--ink)" stroke-width="1.5"/>' + txt(c.X(1951), c.Y(22.8) - 8, '美国的黄金', {s: 11.5, a: 'start', c: 'var(--och)'}) + txt(c.X(1966), c.Y(36), '外国人手里的美元', {s: 11.5, a: 'end', c: 'var(--red)'});
      const cents = Math.min(100, g / f * 100);
      kv($('#gdKV'), [['美国的黄金（按 35 美元）', g.toFixed(1) + ' 十亿'], ['外国人手里的美元', f.toFixed(1) + ' 十亿'], ['大家一起来兑，每一美元能换到', Math.round(cents) + ' 美分的黄金']]);
      say.className = 'say' + (cents < 100 ? ' bad' : ' ok');
      say.innerHTML = cents >= 100 ? '<b>窗口后面的金库是满的。</b>美国的黄金比外国人手里的美元还多，谁来兑都兑得起。“美元和黄金一样好”，这时候是真的。'
        : cents > 40 ? '<b>金库已经不够了，只是大家还没有一起来。</b>特里芬说的那个难题出现了：美元流出去越多，世界越离不开美元，美元越不可信。法国人开始一船一船地把黄金运回家。'
        : '<b>每一美元后面只剩下一二十美分的黄金。</b>这时候窗口开着，就是在等最后一个人来把它搬空。1971 年 8 月，英国人也来要黄金了，尼克松关上了窗口。';
    } else if (tab === 1) {
      const c = lineChart(svg, [{color: 'var(--och)', pts: O.map(r => [r[0], r[1]]), w: 3}, {color: 'var(--red)', pts: O.map(r => [r[0], r[2]]), w: 2.4}, {color: 'var(--main)', pts: O.map(r => [r[0], r[3]]), w: 2.4, dash: '6 3'}],
        {H: 240, xmin: 1970, xmax: 1990, ymin: 0, ymax: 40, xt: [1970, 1975, 1980, 1985, 1990], yt: [0, 10, 20, 30, 40], marks: [[1973.8, '石油禁运'], [1979.6, '沃尔克'], [1985.7, '广场协议']]});
      svg.innerHTML += txt(c.X(1981), c.Y(37.5), '油价（美元/桶）', {s: 11.5, a: 'start', c: 'var(--och)'}) + txt(c.X(1981.3), c.Y(18.5), '联邦基金利率 %', {s: 11.5, a: 'start', c: 'var(--main)'}) + txt(c.X(1975.3), c.Y(12.5), '通胀 %', {s: 11.5, a: 'start', c: 'var(--red)'});
      say.className = 'say';
      say.innerHTML = '<b>两次石油危机，两次通货膨胀。</b>第一次（1973—1974 年）美联储没有下狠手，通胀退下去又回来了；第二次（1979—1980 年）沃尔克把利率拉到了通胀之上很多，代价是 1981—1982 年的大衰退，换来的是此后四十年的低通胀。<em>注意看蓝色的虚线什么时候跑到了红线上面：那就是“下狠手”的意思</em>。';
    } else {
      lineChart(svg, [{color: 'var(--pur)', pts: J, w: 3}], {H: 230, xmin: 1970, xmax: 1990, ymin: 100, ymax: 380, xt: [1970, 1975, 1980, 1985, 1990], yt: [100, 200, 300], yf: v => v + ' 日元', marks: [[1971.6, '尼克松冲击'], [1985.7, '广场协议'], [1989.9, '泡沫顶点']]});
      say.className = 'say';
      say.innerHTML = '<b>二十年里，日元对美元升值了一倍半。</b>布雷顿森林时代固定在三百六十日元换一美元；1985 年广场协议以后两年，跌到了一百二十几日元。日元每升值一次，日本的出口就难一次，日本银行就降一次息，便宜的钱最后涌进了股市和地产。<em>美国的货币政策，常常是别国的天气</em>。';
    }
  }
  go();
});
